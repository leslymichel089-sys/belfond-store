/* ---------- Moteur i18n ---------- */
const BelfondI18n = (function () {
  const KEY = "belfond-lang";
  let lang = "ht";
  try {
    const saved = localStorage.getItem(KEY);
    if (saved === "fr" || saved === "ht") lang = saved;
  } catch (e) { /* stockage indisponible : défaut ht */ }

  function getLang() { return lang; }

  function apply(l) {
    if (!I18N[l]) l = "ht";
    lang = l;
    const d = I18N[l];
    document.documentElement.lang = (l === "fr") ? "fr" : "ht";

    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      const k = el.getAttribute("data-i18n");
      if (d[k] != null) el.textContent = d[k];
    });
    document.querySelectorAll("[data-i18n-html]").forEach(function (el) {
      const k = el.getAttribute("data-i18n-html");
      if (d[k] != null) el.innerHTML = d[k];
    });
    document.querySelectorAll("[data-i18n-alt]").forEach(function (el) {
      const k = el.getAttribute("data-i18n-alt");
      if (d[k] != null) el.setAttribute("alt", d[k]);
    });
    document.querySelectorAll("[data-i18n-aria]").forEach(function (el) {
      const k = el.getAttribute("data-i18n-aria");
      if (d[k] != null) el.setAttribute("aria-label", d[k]);
    });

    const titleEl = document.querySelector("title[data-i18n-title]");
    if (titleEl && d[titleEl.getAttribute("data-i18n-title")] != null) {
      document.title = d[titleEl.getAttribute("data-i18n-title")];
    }
    const descEl = document.querySelector('meta[name="description"][data-i18n-content]');
    if (descEl && d[descEl.getAttribute("data-i18n-content")] != null) {
      descEl.setAttribute("content", d[descEl.getAttribute("data-i18n-content")]);
    }

    document.querySelectorAll(".lang-btn").forEach(function (b) {
      const actif = b.getAttribute("data-lang") === l;
      b.classList.toggle("actif", actif);
      b.setAttribute("aria-pressed", actif ? "true" : "false");
    });

    try { localStorage.setItem(KEY, l); } catch (e) { /* ignore */ }
    window.dispatchEvent(new CustomEvent("belfond:langchange", { detail: { lang: l } }));
  }

  function init() {
    document.querySelectorAll(".lang-btn").forEach(function (b) {
      b.addEventListener("click", function () { apply(b.getAttribute("data-lang")); });
    });
    apply(lang);
  }

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", init);
  } else {
    init();
  }

  return { getLang: getLang, apply: apply, dict: function () { return I18N[lang]; } };
})();

/* Exposition explicite : un « const » de niveau supérieur ne crée pas de
   propriété window — app.js détecte la langue via window.BelfondI18n. */
window.BelfondI18n = BelfondI18n;
